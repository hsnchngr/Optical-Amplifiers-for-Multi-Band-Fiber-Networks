# Self-test of the comparison chain on synthetic input (NOT a simulator result)
# ----------------------------------------------------------------------------------------------------------------
def selftest():
    dev, _ = E.load_device()
    ref = load_reference()
    lam = ref[PUMPS[0]]["lambda_nm"]
    pin = np.full(lam.size, dbm2w(-13.0))
    num = E.Numerics(nz=100, dlam=0.5)               # reference CSV: nz = 200, 0.25-nm bins
    r = E.giles_ase(dev, np.array(PUMPS) * 1e-3, lam, pin, num=num)
    lam_a = r["lam_ase"]
    dnu = E.c * num.dlam * 1e-9 / (lam_a * 1e-9) ** 2
    f = E.c / (lam_a * 1e-9)
    tmp = tempfile.mkdtemp(prefix="e2e_selftest_")
    worst = dict(chain=0.0, gain=0.0, ase=0.0, nf=0.0)
    try:
        for i, p in enumerate(PUMPS):
            pp = R.postprocess(lam, pin, r["G"][i] * pin, f - dnu / 2, f + dnu / 2, r["S_bins"][i] * dnu)
            # 1) post-processing of noise bins reproduces the open model's own ASE and NF (same bins, same rule)
            worst["chain"] = max(worst["chain"],
                                 float(np.max(np.abs(pp["ASE_dBm"] - E.ase_01nm_dBm(r["S"][i], lam)))),
                                 float(np.max(np.abs(pp["NF_dB"] - 10 * np.log10(r["NF"][i])))))
            path = os.path.join(tmp, f"N_P{p:g}mW.csv")
            R.write_run_csv(path, {"run set": "SELFTEST (synthetic, open model nz=100, 0.5-nm bins)"}, lam, pin,
                            r["G"][i] * pin, pp)
        runs = load_runs(tmp)
        res, _ = compare(runs, ref, open_model_W())
        t = res["N_vs_open_model"]
        worst.update(gain=t["gain"]["overall"]["max_abs"], ase=t["ase"]["overall"]["max_abs"],
                     nf=t["nf"]["overall"]["max_abs"])
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("SELFTEST on synthetic input (open model at nz = 100 and 0.5-nm bins written as simulator CSV files):")
    print(f"  noise-bin post-processing vs open model, same bins: max |diff| {worst['chain']:.2e} dB")
    print(f"  CSV round trip + statistics vs open_model_reference.csv (nz = 200, 0.25 nm): max |diff| gain "
          f"{worst['gain']:.2e} dB, ASE {worst['ase']:.3f} dB, NF {worst['nf']:.3f} dB")
    ok = worst["chain"] < 1e-6 and worst["gain"] < 1e-3 and worst["ase"] < 0.05 and worst["nf"] < 0.05
    print("  ->", "PASS" if ok else "FAIL")
    return ok


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(0 if selftest() else 1)
    main()
