def load_runs(runs_dir=R.RUNS):
    """{set: {reported pump: (meta, columns)}} for every run CSV present."""
    out = {}
    for path in sorted(glob.glob(os.path.join(runs_dir, "*_P*mW.csv"))):
        name = os.path.basename(path)[:-4]
        set_name, _, rest = name.partition("_P")
        try:
            p = float(rest[:-2])
        except ValueError:
            continue
        out.setdefault(set_name, {})[p] = R.read_run_csv(path)
    return out


def run_logs(runs_dir=R.RUNS):
    """Summaries of all run logs (attempts), oldest first."""
    logs = []
    paths = glob.glob(os.path.join(runs_dir, "run_log_*.json")) + glob.glob(os.path.join(runs_dir, "attempt_*.json"))
    for path in paths:
        try:
            with open(path, encoding="utf-8") as f:
                L = json.load(f)
        except (OSError, ValueError):
            continue
        logs.append(dict(file=os.path.basename(path), started=L.get("started"), finished=L.get("finished"),
                         argv=L.get("argv"), status=L.get("status"), software=L.get("software"),
                         note=L.get("note") or L.get("annotation_added_2026-11-18"),
                         dialogs=[" | ".join(d.get("text", [])) for d in L.get("dialogs", []) if d.get("text")],
                         sessions=[{k: s.get(k) for k in ("started", "ended", "own_pids", "terminated_own_pids",
                                                         "quit_error", "licence_error")}
                                   for s in L.get("sessions", [])]))
    return sorted(logs, key=lambda d: d.get("started") or "")


def table(sim, ref, pumps):
    pumps = [p for p in pumps if p in sim and p in ref]
    if not pumps:
        return None
    t = E.metrics_table({p: sim[p] for p in pumps}, {p: ref[p] for p in pumps}, pumps)
    t["pumps_mW"] = pumps
    return t


def check_grid(runs, ref):
    """The statistics subtract per channel index: every 40-channel run must use the reference wavelength grid."""
    for set_name, by_p in runs.items():
        for p, (_, cols) in by_p.items():
            if p in ref and cols["lambda_nm"].size == ref[p]["lambda_nm"].size and \
                    not np.allclose(cols["lambda_nm"], ref[p]["lambda_nm"], rtol=0, atol=1e-6):
                raise ValueError(f"{set_name} {p:g} mW: channel wavelengths differ from {REF_CSV}")


def compare(runs, ref, w_ref):
    check_grid(runs, ref)
    res, acc = {}, {}
    col = {"G": "G_dB", "ASE": "ASE_0p1nm_dBm", "NF": "NF_dB"}

    def sim(set_name, q):
        return {p: v[1][col[q]] for p, v in runs.get(set_name, {}).items()}

    for set_name, suffix in (("N", "nominal"), ("C", "calibrated")):
        if set_name not in runs:
            continue
        res[f"{set_name}_vs_open_model"] = {
            "gain": table(sim(set_name, "G"), {p: ref[p][f"G_{suffix}_dB"] for p in PUMPS}, PUMPS),
            "ase": table(sim(set_name, "ASE"), {p: ref[p][f"ASE_{suffix}_dBm"] for p in PUMPS}, PUMPS),
            "nf": table(sim(set_name, "NF"), {p: ref[p][f"NF_{suffix}_dB"] for p in PUMPS}, PUMPS)}
        res[f"{set_name}_vs_measured"] = {
            "gain": table(sim(set_name, "G"), {p: ref[p]["G_measured_dB"] for p in PUMPS}, PUMPS),
            "ase": table(sim(set_name, "ASE"), {p: ref[p]["ASE_measured_dBm"] for p in PUMPS}, PUMPS)}
        g = sim(set_name, "G")
        res[f"{set_name}_mean_gain_dB"] = {f"{p:g}": float(np.mean(g[p])) for p in PUMPS if p in g}
        a = sim(set_name, "ASE")
        res[f"{set_name}_mean_ase_dBm"] = {f"{p:g}": float(np.mean(a[p])) for p in PUMPS if p in a}
    if "W" in runs:
        res["W_vs_open_model"] = {q.lower(): table(sim("W", q), {p: np.atleast_1d(w_ref[p][q]) for p in PUMPS}, PUMPS)
                                  for q in ("G", "ASE", "NF")}
        res["W_gain_dB"] = {f"{p:g}": float(sim("W", "G")[p][0]) for p in PUMPS if p in runs["W"]}
    if "V" in runs:
        t = table(sim("V", "G"), {p: ref[p]["G_eq5_nominal_dB"] for p in PUMPS}, PUMPS)
        acc["C3"] = dict(check="run set V (ASE suppressed) against Equation (5), nominal card, 40 x -13 dBm",
                         max_abs_dB=t["overall"]["max_abs"], rmse_dB=t["overall"]["rmse"],
                         tolerance_dB=R.TOL_C3_DB, passed=bool(t["overall"]["max_abs"] <= R.TOL_C3_DB), table=t)
    if "Nconv" in runs and "N" in runs:
        pc = list(runs["Nconv"])
        res["numerical_Nconv_vs_N"] = {q.lower(): table(sim("N", q), sim("Nconv", q), pc) for q in ("G", "ASE", "NF")}
        res["Nconv_vs_open_model"] = {
            "gain": table(sim("Nconv", "G"), {p: ref[p]["G_nominal_dB"] for p in PUMPS}, pc),
            "ase": table(sim("Nconv", "ASE"), {p: ref[p]["ASE_nominal_dBm"] for p in PUMPS}, pc),
            "nf": table(sim("Nconv", "NF"), {p: ref[p]["NF_nominal_dB"] for p in PUMPS}, pc),
            "N_same_pumps_ase": table(sim("N", "ASE"), {p: ref[p]["ASE_nominal_dBm"] for p in PUMPS}, pc)}
    nf_ref = {"N": {p: ref[p]["NF_nominal_dB"] for p in PUMPS}, "C": {p: ref[p]["NF_calibrated_dB"] for p in PUMPS},
              "W": {p: np.atleast_1d(w_ref[p]["NF"]) for p in PUMPS}}
    for set_name in ("N", "C", "W"):
        if set_name in runs:
            dp = {p: v[1]["NF_dpwdma_dB"] for p, v in runs[set_name].items()}
            gp = {p: v[1]["G_dpwdma_dB"] for p, v in runs[set_name].items()}
            if all(np.isfinite(x).all() for x in dp.values()):
                res[f"{set_name}_nf_dpwdma_vs_bins"] = table(dp, sim(set_name, "NF"), PUMPS)
                res[f"{set_name}_nf_dpwdma_vs_open_model"] = table(dp, nf_ref[set_name], PUMPS)
            if all(np.isfinite(x).all() for x in gp.values()):
                res[f"{set_name}_gain_dpwdma_vs_exported"] = table(gp, sim(set_name, "G"), PUMPS)
    return res, acc


def totals_vs_open_model(ref_json=E.RESULTS_PATH, log_path=R.LOG_PATH):
    """Residual pump at z = L and total backward ASE at z = 0 (nominal card): simulator vs open model."""
    if not os.path.exists(log_path):
        return None
    with open(log_path, encoding="utf-8") as f:
        L = json.load(f)
    with open(ref_json, encoding="utf-8") as f:
        S = json.load(f)["L2"]["spectra"]
    out = {}
    for r in L.get("runs", []):
        if r.get("set") != "N" or "residual_pump_mW" not in r:
            continue
        k = f"{r['pump_reported_mW']:g}"
        out[k] = dict(residual_pump_mW=[r["residual_pump_mW"], S["Pp_out_mW"][k]],
                      backward_ase_total_mW=[r["bins_backward"]["total_mW"], S["Pase_b_mW"][k]])
    for k, v in out.items():
        for q in list(v):
            a, b = v[q]
            v[q] = dict(simulator=a, open_model=b, ratio_dB=float(10 * np.log10(a / b)))
    return out


PLACEMENTS = ("centre", "short_wavelength_edge", "long_wavelength_edge")


def ase_bin_placement(ref, w_ref, runs_dir=R.RUNS):
    """Diagnostic: at which wavelength does an OptiSystem noise bin carry the ASE spectrum?

    (1) Channel ASE in 0.1 nm and NF recomputed from the saved forward-ASE bins at z = L (*.npz) with the PSD of each
        bin (bin power / bin width) placed at the bin centre (= the run CSVs), at its short-wavelength (high-frequency)
        edge or at its long-wavelength edge; statistics against the open model (reference CSV; W: open_model_W) and
        N minus Nconv (18.1 and 114.9 mW).
    (2) Shift of the per-bin PSD (bin centres 1475-1565 nm) that best matches a finely resolved open-model spectrum
        (nz = 400, 1/32-nm bins, same pump and load), with the RMS deviation at the centre and at the short edge."""
    sets = (("N", "nominal", PUMPS), ("C", "calibrated", PUMPS), ("Nconv", "nominal", (18.1, 114.9)), ("W", None, PUMPS))
    out = dict(note="simulator minus open model [dB], RMSE / bias / maximum; the headline comparisons use 'centre'")
    chan = {}
    for place in PLACEMENTS:
        res = {}
        for s, card, pumps in sets:
            A, F, Ar, Fr = {}, {}, {}, {}
            for p in pumps:
                path = os.path.join(runs_dir, f"{s}_P{p:g}mW.npz")
                if not os.path.exists(path):
                    continue
                z = np.load(path)
                lo, hi, P = z["fwd_lo_Hz"], z["fwd_hi_Hz"], z["fwd_P_W"]
                f0 = {"centre": 0.5 * (lo + hi), "short_wavelength_edge": hi, "long_wavelength_edge": lo}[place]
                w = hi - lo
                pp = R.postprocess(z["lambda_nm"], z["pin_W"], z["pout_W"], f0 - w / 2, f0 + w / 2, P)
                A[p], F[p] = pp["ASE_dBm"], pp["NF_dB"]
                if card is None:
                    Ar[p], Fr[p] = np.atleast_1d(w_ref[p]["ASE"]), np.atleast_1d(w_ref[p]["NF"])
                else:
                    Ar[p], Fr[p] = ref[p][f"ASE_{card}_dBm"], ref[p][f"NF_{card}_dB"]
            if A:
                res[s] = dict(ase_vs_open_model=table(A, Ar, list(A)), nf_vs_open_model=table(F, Fr, list(F)))
                if s in ("N", "C"):
                    res[s]["ase_vs_measured"] = table(A, {p: ref[p]["ASE_measured_dBm"] for p in A}, list(A))
                chan[(place, s)] = (A, F)
        if ("N" in res) and ("Nconv" in res):
            (aN, fN), (aC, fC) = chan[(place, "N")], chan[(place, "Nconv")]
            pc = [p for p in aC if p in aN]
            res["N_minus_Nconv"] = dict(ase=table(aN, aC, pc), nf=table(fN, fC, pc))
        out[place] = res
    dev, _ = E.load_device()
    fine = E.Numerics(nz=400, dlam=1.0 / 32, tol_dB=1e-9)
    grid = np.linspace(-0.5, 0.5, 2001)
    shifts = {}
    for s, p in (("N", 18.1), ("N", 114.9), ("Nconv", 18.1), ("Nconv", 114.9), ("W", 18.1), ("W", 114.9)):
        path = os.path.join(runs_dir, f"{s}_P{p:g}mW.npz")
        if not os.path.exists(path):
            continue
        z = np.load(path)
        r = E.giles_ase(dev, [p * 1e-3], z["lambda_nm"], z["pin_W"], num=fine)
        lam_f, S_f = r["lam_ase"], r["S_bins"][0]
        lo, hi, P = z["fwd_lo_Hz"], z["fwd_hi_Hz"], z["fwd_P_W"]
        cen = R.C0 / (0.5 * (lo + hi)) * 1e9
        half = float(np.mean(0.5 * (R.C0 / lo - R.C0 / hi) * 1e9))
        S = P / (hi - lo)
        sel = (cen > 1475.0) & (cen < 1565.0)

        def rms(d):
            return float(np.sqrt(np.mean((10 * np.log10(S[sel] / np.interp(cen[sel] + d, lam_f, S_f))) ** 2)))

        rr = np.array([rms(d) for d in grid])
        k = int(np.argmin(rr))
        shifts[f"{s} {p:g}"] = dict(bin_width_nm=2 * half, best_shift_nm=float(grid[k]), rms_at_best_dB=float(rr[k]),
                                    rms_at_centre_dB=rms(0.0), rms_at_short_wavelength_edge_dB=rms(-half))
    out["per_bin_psd_shift_vs_fine_open_model"] = dict(
        note="negative shift = the bin carries the open-model spectrum at a shorter wavelength than its centre",
        runs=shifts)
    return out


def c1_result():
    path = os.path.join(R.RUNS, "C1_absorption.csv")
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        lines = [ln.strip() for ln in f if ln.strip()]
    meta = [ln for ln in lines if ln.startswith("#")]
    rows = [ln for ln in lines if not ln.startswith("#")]
    d = np.array([[float(x) for x in ln.split(",")] for ln in rows[1:]])
    probe, card, sim8, rel8, sim1, rel1 = d[:, 0], d[:, 1], d[:, 2], d[:, 3], d[:, 5], d[:, 6]
    om = open_model_C1(probe)
    return dict(header=meta, n_probes=int(probe.size),
                max_abs_rel_dev_8m=float(np.max(np.abs(rel8))), max_abs_rel_dev_1m=float(np.max(np.abs(rel1))),
                open_model_pump_off_vs_card_max_rel_dev_8m=float(np.max(np.abs(om[8.0]["alpha_dB_per_m"] / card - 1))),
                simulator_vs_open_model_pump_off_max_rel_dev_8m=float(np.max(np.abs(sim8 / om[8.0]["alpha_dB_per_m"]
                                                                                     - 1))),
                simulator_vs_open_model_pump_off_max_rel_dev_1m=float(np.max(np.abs(sim1 / om[1.0]["alpha_dB_per_m"]
                                                                                     - 1))))


def expected_open_model(ref, w_ref):
    """Open-model values (nominal card, internal planes) that the simulator run should reproduce."""
    return dict(
        note="open ASE-resolved model, e2e_perin.giles_ase (nz = 200, 0.25-nm ASE bins), internal planes",
        mean_gain_N_dB={f"{p:g}": float(np.mean(ref[p]["G_nominal_dB"])) for p in PUMPS},
        mean_ase_N_dBm={f"{p:g}": float(np.mean(ref[p]["ASE_nominal_dBm"])) for p in PUMPS},
        max_nf_N_dB={f"{p:g}": float(np.max(ref[p]["NF_nominal_dB"])) for p in PUMPS},
        mean_gain_C_dB={f"{p:g}": float(np.mean(ref[p]["G_calibrated_dB"])) for p in PUMPS},
        eq5_minus_ase_model_N=E.stats(np.concatenate([ref[p]["G_eq5_nominal_dB"] - ref[p]["G_nominal_dB"]
                                                      for p in PUMPS])),
        W_gain_dB={f"{p:g}": float(w_ref[p]["G"][0]) for p in PUMPS},
        W_gain_eq5_dB={f"{p:g}": float(w_ref[p]["G_eq5"][0]) for p in PUMPS},
        W_ase_dBm={f"{p:g}": float(w_ref[p]["ASE"][0]) for p in PUMPS},
        W_nf_dB={f"{p:g}": float(w_ref[p]["NF"][0]) for p in PUMPS},
        open_model_vs_measured_gain_N=E.stats(np.concatenate([ref[p]["G_nominal_dB"] - ref[p]["G_measured_dB"]
                                                              for p in PUMPS])),
        open_model_vs_measured_ase_N=E.stats(np.concatenate([ref[p]["ASE_nominal_dBm"] - ref[p]["ASE_measured_dBm"]
                                                             for p in PUMPS])),
        open_model_calibrated_vs_measured_gain=E.stats(np.concatenate([ref[p]["G_calibrated_dB"] -
                                                                       ref[p]["G_measured_dB"] for p in PUMPS])),
        open_model_calibrated_vs_measured_ase=E.stats(np.concatenate([ref[p]["ASE_calibrated_dBm"] -
                                                                      ref[p]["ASE_measured_dBm"] for p in PUMPS])))


def fmt(t, key="overall"):
    if not t:
        return "n/a"
    o = t[key]
    return f"{o['rmse']:.3f} / {o['bias']:+.3f} / {o['max_abs']:.3f}"


def main():
    ref = load_reference()
    w_ref = open_model_W()
    runs = load_runs()
    logs = run_logs()
    last = logs[-1] if logs else None
    expected = {"N": 6, "C": 6, "W": 6, "V": 6}
    have = {k: len(runs.get(k, {})) for k in expected}
    if not any(have.values()):
        status = "not run"
    elif all(have[k] == n for k, n in expected.items()):
        status = "complete"
    else:
        status = "partial"
    out = dict(figure="E2E_simulator", script="e2e_simulator_compare.py", date=time.strftime("%Y-%m-%d"),
               status=status, runs_found=have,
               simulator=dict(software=(last or {}).get("software"), component="Er Doped Fiber (steady state)",
                              route="A: Giles coefficients in dB/m and saturation parameter; overlap fixed at 1 "
                                    "(file); see run_optisystem_perin2019.py",
                              script="run_optisystem_perin2019.py", inputs="notes/optisystem_perin2019/runs/inputs"),
               attempts=logs, expected_open_model=expected_open_model(ref, w_ref))
    plan_path = os.path.join(R.INPUTS, "plan.json")
    if os.path.exists(plan_path):
        with open(plan_path, encoding="utf-8") as f:
            out["acceptance"] = {"C2": json.load(f).get("C2")}
    if status == "not run":
        reason = (last or {}).get("status") or "run_optisystem_perin2019.py has not been run"
        out["reason"] = reason
        out["error_budget_row"] = dict(
            contribution="Independent simulator (OptiSystem 23.1, 'Er Doped Fiber', same card and operating points)",
            gain="not available: simulator not run (" + reason.split(":")[0] + ")", ase="not available")
    else:
        res, acc = compare(runs, ref, w_ref)
        res["ase_bin_placement"] = ase_bin_placement(ref, w_ref)
        out["comparisons"] = res
        out["totals_vs_open_model_N"] = totals_vs_open_model()
        out.setdefault("acceptance", {}).update(acc)
        c1 = c1_result()
        if c1:
            out["acceptance"]["C1"] = c1
        if os.path.exists(R.LOG_PATH):
            with open(R.LOG_PATH, encoding="utf-8") as f:
                L = json.load(f)
            out["run"] = dict(started=L.get("started"), status=L.get("status"), software=L.get("software"),
                              C1_rule=L.get("C1", {}).get("rule"),
                              ase_checks={f"{r['set']} {r['pump_reported_mW']:g}": r.get("ase_check")
                                          for r in L.get("runs", [])},
                              seconds_per_run=[r.get("seconds") for r in L.get("runs", [])])
        n_open, n_meas = res.get("N_vs_open_model", {}), res.get("N_vs_measured", {})
        c_open, c_meas = res.get("C_vs_open_model", {}), res.get("C_vs_measured", {})
        w_open = res.get("W_vs_open_model", {})
