def load_reference(path=REF_CSV):
    """Open-model and measured values per reported pump power (40 channels each)."""
    with open(path, encoding="utf-8") as f:
        lines = [ln.strip() for ln in f if ln.strip() and not ln.startswith("#")]
    header = lines[0].split(",")
    d = np.array([[float(x) for x in ln.split(",")] for ln in lines[1:]])
    col = {h: d[:, i] for i, h in enumerate(header)}
    out = {}
    for p in PUMPS:
        s = np.isclose(col["pump_reported_mW"], p)
        out[p] = {h: col[h][s] for h in header}
        if s.sum() != 40:
            raise ValueError(f"{path}: {s.sum()} rows for {p} mW")
    return out


def open_model_W():
    """Open model for run set W (1 channel at 1550 nm, -40 dBm): ASE-resolved model and Equation (5)."""
    dev, _ = E.load_device()
    lam = np.array([R.W_LAMBDA_NM])
    g = E.predict(dev, PUMPS, lam, model="giles", p_ch_dBm=10 * np.log10(R.W_P_MW))
    s = E.predict(dev, PUMPS, lam, model="saleh", p_ch_dBm=10 * np.log10(R.W_P_MW))
    return {p: dict(G=g["G_dB"][i], ASE=g["ASE_dBm"][i], NF=g["NF_dB"][i], G_eq5=s["G_dB"][i])
            for i, p in enumerate(PUMPS)}


def open_model_C1(probe_nm, lengths=(8.0, 1.0)):
    """Open-model pump-off absorption at the C1 probe set and probe power (bias of the probe-induced inversion)."""
    dev, _ = E.load_device()
    out = {}
    pw = R.P_PROBE_MW * 1e-3
    for L in lengths:
        r = E.giles_ase(dev, [pw], np.asarray(probe_nm, float), pw, L=[L], num=E.Numerics(nz=400, dlam=0.25))
        out[L] = dict(alpha_dB_per_m=-10 * np.log10(r["G"][0]) / L,
                      alpha_980_dB_per_m=float(-10 * np.log10(r["Pp_out"][0] / pw) / L))
    return out


